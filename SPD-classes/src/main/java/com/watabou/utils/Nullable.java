package com.watabou.utils;

import java.lang.annotation.ElementType;
import java.lang.annotation.Retention;
import java.lang.annotation.RetentionPolicy;
import java.lang.annotation.Target;

/**
 * Marks a field, parameter, or return value that may legitimately be null.
 *
 * NullAway matches nullability annotations by simple name, so this project-local
 * annotation avoids a jspecify dependency. Retention is CLASS, not RUNTIME, so
 * nothing reaches the Android or RoboVM runtime classpath.
 */
@Retention(RetentionPolicy.CLASS)
@Target({ ElementType.FIELD, ElementType.METHOD, ElementType.PARAMETER, ElementType.LOCAL_VARIABLE })
public @interface Nullable {
}
